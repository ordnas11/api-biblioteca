

DROP DATABASE IF EXISTS biblioteca;
CREATE DATABASE biblioteca CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE biblioteca;


CREATE TABLE aluno (
    CPF_ALUNO       VARCHAR(11)  NOT NULL PRIMARY KEY,
    NOME_ALUNO      VARCHAR(150) NOT NULL,
    RA_ALUNO        VARCHAR(9)   NOT NULL UNIQUE,
    DATA_NASCIMENTO DATE         NOT NULL
);

CREATE TABLE atendente (
    CPF_ATENDENTE  VARCHAR(11)  NOT NULL PRIMARY KEY,
    NOME_ATENDENTE VARCHAR(150) NOT NULL,
    MATRICULA      VARCHAR(10)  NOT NULL UNIQUE,
    TELEFONE       VARCHAR(15)
);

CREATE TABLE livro (
    ID_LIVRO       INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
    TITULO_LIVRO   VARCHAR(200) NOT NULL,
    AUTOR_LIVRO    VARCHAR(150) NOT NULL,
    EDITORA        VARCHAR(100),
    ANO_PUBLICACAO INT
);


CREATE TABLE exemplar (
    ID_EXEMPLAR     INT         NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ID_LIVRO        INT         NOT NULL,
    CODIGO_BARRAS   VARCHAR(20) NOT NULL UNIQUE,
    STATUS_EXEMPLAR VARCHAR(15) NOT NULL DEFAULT 'DISPONIVEL',
    DATA_AQUISICAO  DATE,
    CONSTRAINT fk_exemplar_livro
        FOREIGN KEY (ID_LIVRO) REFERENCES livro(ID_LIVRO),
    CONSTRAINT chk_status_exemplar
        CHECK (STATUS_EXEMPLAR IN ('DISPONIVEL', 'EMPRESTADO'))  -- MySQL 8.0.16+
);


CREATE TABLE emprestimo (
    ID_EMPRESTIMO   INT         NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CPF_ALUNO       VARCHAR(11) NOT NULL,
    ID_EXEMPLAR     INT         NOT NULL,
    CPF_ATENDENTE   VARCHAR(11) NOT NULL,
    DATA_EMPRESTIMO DATE        NOT NULL,
    DATA_DEVOLUCAO  DATE        NOT NULL,  -- data prevista
    DATA_ENTREGA    DATE,                  -- NULL = ainda emprestado
    CONSTRAINT fk_emp_aluno
        FOREIGN KEY (CPF_ALUNO)     REFERENCES aluno(CPF_ALUNO),
    CONSTRAINT fk_emp_exemplar
        FOREIGN KEY (ID_EXEMPLAR)   REFERENCES exemplar(ID_EXEMPLAR),
    CONSTRAINT fk_emp_atendente
        FOREIGN KEY (CPF_ATENDENTE) REFERENCES atendente(CPF_ATENDENTE),
    CONSTRAINT chk_datas_emprestimo
        CHECK (DATA_DEVOLUCAO >= DATA_EMPRESTIMO)
);

DELIMITER //
CREATE TRIGGER trg_exemplar_unico
BEFORE INSERT ON emprestimo
FOR EACH ROW
BEGIN
    IF EXISTS (SELECT 1 FROM emprestimo
               WHERE ID_EXEMPLAR = NEW.ID_EXEMPLAR
                 AND DATA_ENTREGA IS NULL) THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Exemplar já está emprestado a outro aluno.';
    END IF;
END//
DELIMITER ;


SHOW TABLES;